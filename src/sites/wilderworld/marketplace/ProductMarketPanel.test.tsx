import {act,cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react';
import {afterEach,describe,expect,it,vi} from 'vitest';
import ProductMarketPanel from './ProductMarketPanel';
import {marketTargetKey,USD,type MarketReadAdapter} from './market-data';

afterEach(()=>{cleanup();vi.useRealTimers();});
describe('product market preview',()=>{
  it('shows populated clearly labeled demo trading by default without executing transactions',async()=>{
    render(<ProductMarketPanel productId="item-1" variantId="finish-1" variantName="Silver" previewPriceCents={1200}/>);
    await waitFor(()=>expect(screen.getByRole('status').textContent).toMatch(/SAMPLE DATA/));
    expect(screen.getAllByText('SAMPLE DATA')).toHaveLength(2);
    expect(screen.getByText('Demo seller 01')).toBeTruthy();
    expect(screen.getByText('Demo buyer 01')).toBeTruthy();
    expect(screen.getByRole('img',{name:/Sample price chart/})).toBeTruthy();
    fireEvent.click(screen.getByRole('tab',{name:'Trade history'}));
    expect(screen.getByText('Demo sale 01')).toBeTruthy();
    expect(screen.getByText(/No blockchain transactions/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button',{name:'Review purchase'}));
    expect(screen.getByText(/No payment or ownership transfer/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button',{name:'View live data'}));
    expect(screen.queryByText('SAMPLE DATA')).toBeNull();
    expect(screen.getByRole('status').textContent).toMatch(/not connected/);
    expect((screen.getByRole('button',{name:'Buy now'}) as HTMLButtonElement).disabled).toBe(true);
  });
  it('saves only a local draft and clears it when the selected finish changes',async()=>{
    const {rerender}=render(<ProductMarketPanel productId="item-1" variantId="finish-1" variantName="Silver"/>);
    await waitFor(()=>expect(screen.getByRole('status').textContent).toMatch(/SAMPLE DATA/));
    fireEvent.click(screen.getByRole('button',{name:'Draft a bid'}));
    fireEvent.change(screen.getByLabelText(/Your bid/),{target:{value:'12.34'}});
    fireEvent.click(screen.getByRole('button',{name:'Save draft'}));
    expect(screen.getByText(/No order was placed/)).toBeTruthy();
    rerender(<ProductMarketPanel productId="item-1" variantId="finish-2" variantName="Gold"/>);
    expect(screen.queryByText(/No order was placed/)).toBeNull();
    expect(screen.queryByLabelText(/Your bid/)).toBeNull();
    fireEvent.click(screen.getByRole('tab',{name:'Sell / List'}));
    fireEvent.click(screen.getByRole('button',{name:'Review sale'}));
    expect(screen.getByText('Sample sale')).toBeTruthy();
    expect(screen.getByText(/No payment or ownership transfer/)).toBeTruthy();
  });
  it('removes a stale ask at its freshness deadline without user interaction',async()=>{
    vi.useFakeTimers();vi.setSystemTime(new Date('2026-11-07T10:00:00Z'));
    const adapter:MarketReadAdapter={id:'local-test',async read(target){return {target,status:'live',provider:'local-test',asOf:'2026-11-07T10:00:00Z',currency:USD,historyWindow:null,message:'Local fixture',trades:[],orders:[{id:'ask-test',targetKey:marketTargetKey(target),side:'ask',price:{amount:'1234',currency:USD},maker:'0x'+'22'.repeat(20),createdAt:'2026-11-07T09:00:00Z',checkedAt:'2026-11-07T09:59:45Z',expiresAt:'2026-11-07T11:00:00Z',status:'active',provider:'local-test'}]};}};
    await act(async()=>{render(<ProductMarketPanel productId="minted-item" variantId="edition-1" variantName="Silver" identity={{chainId:1,contract:'0x'+'11'.repeat(20),tokenId:'1'}} adapter={adapter}/>);});
    expect(screen.getAllByText('$12.34').length).toBeGreaterThan(0);
    await act(async()=>{vi.advanceTimersByTime(45_002);});
    expect(screen.queryByText('$12.34')).toBeNull();
    expect(screen.getByText('No current asks')).toBeTruthy();
  });
  it('deducts the approved seller fee in drafts without adding a buyer fee or enabling trading',async()=>{
    render(<ProductMarketPanel productId="item-1" variantId="finish-1" variantName="Silver"/>);
    fireEvent.click(screen.getByRole('tab',{name:'Sell / List'}));
    fireEvent.click(screen.getByRole('button',{name:'Draft a listing'}));
    fireEvent.change(screen.getByLabelText(/Your asking price/),{target:{value:'100.00'}});
    fireEvent.click(screen.getByRole('button',{name:'Save draft'}));
    const seller=within(screen.getByLabelText('Marketplace fee preview'));
    expect(seller.getByText('Seller marketplace fee · 1%')).toBeTruthy();
    expect(seller.getByText('1 WILD')).toBeTruthy();
    expect(seller.getByText('99 WILD')).toBeTruthy();
    expect(seller.getByText(/royalties, payment and network costs are separate/)).toBeTruthy();
    fireEvent.click(screen.getByRole('tab',{name:'Buy / Bid'}));
    fireEvent.click(screen.getByRole('button',{name:'Draft a bid'}));
    fireEvent.change(screen.getByLabelText(/Your bid/),{target:{value:'100.00'}});
    fireEvent.click(screen.getByRole('button',{name:'Save draft'}));
    const buyer=within(screen.getByLabelText('Marketplace fee preview'));
    expect(buyer.getByText('Buyer marketplace fee · 0%')).toBeTruthy();
    expect(buyer.getByText('$0.00')).toBeTruthy();
    expect(buyer.getByText('$100.00')).toBeTruthy();
    fireEvent.click(screen.getByRole('button',{name:'View live data'}));
    expect(screen.getByRole('button',{name:'Buy now'})).toBeDisabled();
    fireEvent.click(screen.getByRole('tab',{name:'Sell / List'}));
    expect(screen.getByRole('button',{name:'Sell now'})).toBeDisabled();
  });
  it('offers USD or WILD for purchases, with one explicit demo conversion and no buyer surcharge',()=>{
    render(<ProductMarketPanel productId="item-1" variantId="finish-1" variantName="Silver" previewPriceCents={1200}/>);
    fireEvent.click(screen.getByRole('button',{name:'Review purchase'}));
    const usd=screen.getByLabelText('Marketplace fee preview').textContent!;
    const usdPurchase=Number(usd.match(/Purchase amount\$([\d,.]+)/)![1].replaceAll(',',''));
    fireEvent.click(screen.getByRole('button',{name:'WILD'}));
    const wild=within(screen.getByLabelText('Marketplace fee preview'));
    expect(wild.getByText('0 WILD')).toBeTruthy();
    expect(wild.getByText(`${Math.round(usdPurchase*10).toLocaleString('en-US')} WILD`)).toBeTruthy();
    expect(screen.getByText('Demo conversion: 1 WILD = $0.10. Not a live rate.')).toBeTruthy();
    fireEvent.click(screen.getByRole('tab',{name:'Sell / List'}));
    expect(screen.queryByRole('button',{name:'USD'})).toBeNull();
    expect(screen.getByText('Listings are priced in WILD.')).toBeTruthy();
  });
  it('clears draft amounts when switching currencies so values are never reinterpreted',()=>{
    render(<ProductMarketPanel productId="item-1" variantId="finish-1" variantName="Silver"/>);
    fireEvent.click(screen.getByRole('button',{name:'Draft a bid'}));
    fireEvent.change(screen.getByLabelText(/Your bid/),{target:{value:'100'}});
    fireEvent.click(screen.getByRole('button',{name:'Save draft'}));
    expect(screen.getByText(/Draft saved in this view: \$100.00/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button',{name:'WILD'}));
    expect(screen.getByLabelText(/Your bid/)).toHaveValue('');
    expect(screen.queryByText(/Draft saved/)).toBeNull();
    fireEvent.change(screen.getByLabelText(/Your bid/),{target:{value:'100'}});
    fireEvent.click(screen.getByRole('button',{name:'Save draft'}));
    expect(screen.getByText(/100 WILD. Approx. \$10.00 at the demo rate/)).toBeTruthy();
    fireEvent.click(screen.getByRole('tab',{name:'Sell / List'}));
    fireEvent.click(screen.getByRole('button',{name:'Draft a listing'}));
    expect(screen.getByLabelText(/Your asking price/)).toHaveValue('');
  });
});
